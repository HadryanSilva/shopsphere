package br.com.hadryan.shosphere.order.persistence;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.springframework.boot.autoconfigure.AutoConfigurations;
import org.springframework.boot.flyway.autoconfigure.FlywayAutoConfiguration;
import org.springframework.boot.test.context.runner.ApplicationContextRunner;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import javax.sql.DataSource;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

@EnabledIfEnvironmentVariable(named = "SHOPSPHERE_TEST_POSTGRES_URL", matches = ".+")
class OrderFlywayMigrationTests {
    @Test
    void startupMigratesFreshSchemaAndDoesNotReapplyMigrationsOnRestart() throws Exception {
        var dataSource = new DriverManagerDataSource(System.getenv("SHOPSPHERE_TEST_POSTGRES_URL"),
                System.getenv().getOrDefault("SHOPSPHERE_TEST_POSTGRES_USER", "postgres"),
                System.getenv().getOrDefault("SHOPSPHERE_TEST_POSTGRES_PASSWORD", "postgres"));
        var schema = "order_flyway_test_" + UUID.randomUUID().toString().replace("-", "");
        var runner = new ApplicationContextRunner()
                .withConfiguration(AutoConfigurations.of(FlywayAutoConfiguration.class))
                .withBean(DataSource.class, () -> dataSource)
                .withPropertyValues("spring.flyway.schemas=" + schema, "spring.flyway.default-schema=" + schema);

        try {
            runner.run(context -> {
                assertThat(context).hasNotFailed().hasSingleBean(Flyway.class);
                var info = context.getBean(Flyway.class).info();
                assertThat(info.pending()).isEmpty();
                assertThat(info.applied()).isNotEmpty();
            });

            try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
                try (var result = statement.executeQuery("SELECT count(*) FROM " + schema + ".orders")) {
                    assertThat(result.next()).isTrue();
                    assertThat(result.getInt(1)).isZero();
                }
                try (var result = statement.executeQuery("SELECT count(*) FROM " + schema + ".order_items")) {
                    assertThat(result.next()).isTrue();
                    assertThat(result.getInt(1)).isZero();
                }
            }

            runner.run(context -> {
                assertThat(context).hasNotFailed();
                assertThat(context.getBean(Flyway.class).migrate().migrationsExecuted).isZero();
            });
        } finally {
            // Only remove the schema generated by this test; never clean the configured database.
            try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
                statement.execute("DROP SCHEMA IF EXISTS " + schema + " CASCADE");
            }
        }
    }
}
