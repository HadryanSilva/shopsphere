package br.com.hadryan.shopsphere.catalog.persistence;

import br.com.hadryan.shopsphere.catalog.model.Category;
import br.com.hadryan.shopsphere.catalog.model.Product;
import org.flywaydb.core.Flyway;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.model.naming.PhysicalNamingStrategySnakeCaseImpl;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;

import java.sql.DriverManager;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@EnabledIfEnvironmentVariable(named = "SHOPSPHERE_TEST_POSTGRES_URL", matches = ".+")
class CatalogSchemaMigrationTests {
    @Test
    void upgradesExistingSchemaPreservesVersionAndPassesHibernateValidation() throws Exception {
        var url = System.getenv("SHOPSPHERE_TEST_POSTGRES_URL");
        var username = System.getenv().getOrDefault("SHOPSPHERE_TEST_POSTGRES_USER", "postgres");
        var password = System.getenv().getOrDefault("SHOPSPHERE_TEST_POSTGRES_PASSWORD", "postgres");
        var schema = "catalog_schema_test_" + UUID.randomUUID().toString().replace("-", "");

        try (var connection = DriverManager.getConnection(url, username, password)) {
            // Only the schema generated by this test is created and removed.
            try {
                Flyway.configure().dataSource(url, username, password).schemas(schema).defaultSchema(schema)
                        .locations("classpath:db/migration").target("2").load().migrate();

                try (var statement = connection.createStatement()) {
                    statement.execute("INSERT INTO " + schema + ".products "
                            + "(id, name, category_id, price, version, image_url) VALUES "
                            + "('20000000-0000-0000-0000-000000000001', 'Existing product', "
                            + "'10000000-0000-0000-0000-000000000001', 10.00, 7, 'https://example.test/product')");
                }

                Flyway.configure().dataSource(url, username, password).schemas(schema).defaultSchema(schema)
                        .locations("classpath:db/migration").load().migrate();

                try (var statement = connection.prepareStatement(
                        "SELECT data_type FROM information_schema.columns "
                                + "WHERE table_schema = ? AND table_name = 'products' AND column_name = 'version'")) {
                    statement.setString(1, schema);
                    try (var result = statement.executeQuery()) {
                        assertTrue(result.next());
                        assertEquals("bigint", result.getString(1));
                    }
                }

                var registry = new StandardServiceRegistryBuilder()
                        .applySetting("hibernate.connection.url", url)
                        .applySetting("hibernate.connection.username", username)
                        .applySetting("hibernate.connection.password", password)
                        .applySetting("hibernate.default_schema", schema)
                        .applySetting("hibernate.hbm2ddl.auto", "validate")
                        .applySetting("hibernate.physical_naming_strategy", PhysicalNamingStrategySnakeCaseImpl.class)
                        .build();
                try {
                    try (var factory = new MetadataSources(registry).addAnnotatedClass(Product.class)
                            .addAnnotatedClass(Category.class).buildMetadata().buildSessionFactory();
                         var session = factory.openSession()) {
                        var transaction = session.beginTransaction();
                        var product = session.find(Product.class,
                                UUID.fromString("20000000-0000-0000-0000-000000000001"));
                        assertNotNull(product);
                        assertEquals(7L, product.getVersion());
                        assertEquals("https://example.test/product", product.getImageUrl());
                        product.setName("Updated product");
                        product.setImageUrl("https://example.test/" + "a".repeat(1000));
                        session.flush();
                        session.clear();
                        var updated = session.find(Product.class, product.getId());
                        assertEquals(8L, updated.getVersion());
                        assertEquals(product.getImageUrl(), updated.getImageUrl());
                        transaction.commit();
                    }
                } finally {
                    StandardServiceRegistryBuilder.destroy(registry);
                }
            } finally {
                try (var statement = connection.createStatement()) {
                    statement.execute("DROP SCHEMA IF EXISTS " + schema + " CASCADE");
                }
            }
        }
    }
}
