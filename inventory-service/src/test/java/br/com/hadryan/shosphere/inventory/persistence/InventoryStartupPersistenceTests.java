@EnabledIfEnvironmentVariable(named = "SHOPSPHERE_TEST_POSTGRES_URL", matches = ".+")
class InventoryStartupPersistenceTests {
    private DriverManagerDataSource dataSource;
    private String schema;
    private ApplicationContextRunner runner;

    @BeforeEach
    void setUp() {
        dataSource = new DriverManagerDataSource(System.getenv("SHOPSPHERE_TEST_POSTGRES_URL"),
                System.getenv().getOrDefault("SHOPSPHERE_TEST_POSTGRES_USER", "postgres"),
                System.getenv().getOrDefault("SHOPSPHERE_TEST_POSTGRES_PASSWORD", "postgres"));
        schema = "inventory_startup_test_" + UUID.randomUUID().toString().replace("-", "");
        runner = new ApplicationContextRunner()
                .withInitializer(new ConfigDataApplicationContextInitializer())
                .withUserConfiguration(InventoryServiceApplication.class)
                .withBean(InventoryTestComponentFilter.class, InventoryTestComponentFilter::new)
                .withBean(DataSource.class, () -> dataSource)
                .withBean(JwtDecoder.class, () -> mock(JwtDecoder.class))
                .withPropertyValues("spring.flyway.schemas=" + schema,
                        "spring.flyway.default-schema=" + schema,
                        "services.catalog.url=http://catalog.invalid",
                        "spring.jpa.properties.hibernate.default_schema=" + schema);
    }

    @AfterEach
    void tearDown() throws Exception {
        // Only the schema generated by this test is removed; never clean the configured database.
        if (schema != null) {
            try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
                statement.execute("DROP SCHEMA IF EXISTS " + schema + " CASCADE");
            }
        }
    }

    @Test
    void migratesAndValidatesStockAndPreservesDataAcrossRestart() throws Exception {
        var productId = UUID.randomUUID();
        for (int startup = 0; startup < 2; startup++) {
            var firstStartup = startup == 0;
            runner.run(context -> {
                assertThat(context).hasNotFailed().hasSingleBean(Flyway.class)
                        .hasSingleBean(EntityManagerFactory.class);
                var flyway = context.getBean(Flyway.class);
                assertThat(flyway.getConfiguration().getDataSource()).isSameAs(dataSource);
                assertThat(flyway.info().applied()).filteredOn(migration -> migration.getVersion() != null)
                        .extracting(migration -> migration.getVersion().toString()).containsExactly("1", "2", "3", "4", "5");
                assertThat(flyway.info().pending()).isEmpty();
                assertThat(flyway.migrate().migrationsExecuted).isZero();
                assertThat(context.getBean(EntityManagerFactory.class).getProperties())
                        .containsEntry("hibernate.hbm2ddl.auto", "validate");
                var repository = context.getBean(InventoryStockRepository.class);
                if (firstStartup) {
                    repository.saveAndFlush(new InventoryStock(productId, 7));
                }
                var stored = repository.findById(productId).orElseThrow();
                assertThat(stored.getProductId()).isEqualTo(productId);
                assertThat(stored.getOnHand()).isEqualTo(7);
                assertThat(stored.getReserved()).isZero();
                assertThat(stored.getAvailable()).isEqualTo(7);
                assertThat(stored.getVersion()).isZero();
                assertThat(stored.getCreatedAt()).isNotNull();
                assertThat(stored.getUpdatedAt()).isNotNull();
            });
        }
        try (var connection = dataSource.getConnection(); var query = connection.prepareStatement(
                "SELECT table_name FROM information_schema.tables WHERE table_schema = ?")) {
            query.setString(1, schema);
            try (var result = query.executeQuery()) {
                var tables = new ArrayList<String>();
                while (result.next()) {
                    tables.add(result.getString(1));
                }
                assertThat(tables).containsExactlyInAnyOrder("flyway_schema_history", "inventory_stock", "inventory_movements",
                        "inventory_reservations", "inventory_reservation_items", "inventory_reservation_coordination",
                        "inventory_reservation_coordination_items");
            }
        }
    }

    @Test
    void readsValidQuantityBoundariesAndComputesAvailabilityWithoutCatalog() {
        runner.run(context -> {
            assertThat(context).hasNotFailed();
            var repository = context.getBean(InventoryStockRepository.class);
            for (var quantities : new int[][] {{0, 0}, {Integer.MAX_VALUE, 0},
                    {Integer.MAX_VALUE, Integer.MAX_VALUE}, {10, 3}}) {
                var productId = UUID.randomUUID();
                try (var connection = dataSource.getConnection(); var insert = connection.prepareStatement(
                        "INSERT INTO " + schema + ".inventory_stock (product_id, on_hand, reserved) VALUES (?, ?, ?)")) {
                    insert.setObject(1, productId);
                    insert.setInt(2, quantities[0]);
                    insert.setInt(3, quantities[1]);
                    insert.executeUpdate();
                }
                var stored = repository.findById(productId).orElseThrow();
                assertThat(stored.getOnHand()).isEqualTo(quantities[0]);
                assertThat(stored.getReserved()).isEqualTo(quantities[1]);
                assertThat(stored.getAvailable()).isEqualTo(quantities[0] - quantities[1]);
            }
        });
    }

    @Test
    void upgradesV1WithoutChangingExistingStockOrInventingInitialMovements() throws Exception {
        Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema).target("1").load().migrate();
        var productId = UUID.randomUUID();
        try (var connection = dataSource.getConnection(); var insert = connection.prepareStatement(
                "INSERT INTO " + schema + ".inventory_stock (product_id, on_hand, reserved, version) VALUES (?, 10, 3, 4)")) {
            insert.setObject(1, productId);
            insert.executeUpdate();
        }
        runner.run(context -> {
            assertThat(context).hasNotFailed();
            var stock = context.getBean(InventoryStockRepository.class).findById(productId).orElseThrow();
            assertThat(stock.getOnHand()).isEqualTo(10);
            assertThat(stock.getReserved()).isEqualTo(3);
            assertThat(stock.getAvailable()).isEqualTo(7);
            assertThat(stock.getVersion()).isEqualTo(4L);
            assertThat(context.getBean(InventoryMovementRepository.class).count()).isZero();
            assertThat(context.getBean(Flyway.class).info().pending()).isEmpty();
        });
    }

    @ParameterizedTest
    @CsvSource({"-1,0,23514", "0,-1,23514", "1,2,23514", "2147483648,0,22003", "0,2147483648,22003"})
    void databaseRejectsInvalidCountersEvenWithoutJpa(long onHand, long reserved, String sqlState) {
        runner.run(context -> {
            assertThat(context).hasNotFailed();
            try (var connection = dataSource.getConnection(); var insert = connection.prepareStatement(
                    "INSERT INTO " + schema + ".inventory_stock (product_id, on_hand, reserved) VALUES (?, ?, ?)")) {
                insert.setObject(1, UUID.randomUUID());
                insert.setLong(2, onHand);
                insert.setLong(3, reserved);
                var failure = assertThrows(SQLException.class, insert::executeUpdate);
                assertThat(failure.getSQLState()).isEqualTo(sqlState);
            }
        });
    }

    @Test
    void duplicateProductCannotOverwritePreviouslyPersistedStock() {
        runner.run(context -> {
            assertThat(context).hasNotFailed();
            var repository = context.getBean(InventoryStockRepository.class);
            var productId = UUID.randomUUID();
            repository.saveAndFlush(new InventoryStock(productId, 7));

            assertThrows(DataIntegrityViolationException.class,
                    () -> repository.saveAndFlush(new InventoryStock(productId, 99)));
            assertThat(repository.findById(productId).orElseThrow().getOnHand()).isEqualTo(7);
            assertThat(repository.count()).isEqualTo(1);
        });
    }

    @Test
    void optimisticVersionRejectsStaleWrite() {
        runner.run(context -> {
            assertThat(context).hasNotFailed();
            var repository = context.getBean(InventoryStockRepository.class);
            var productId = UUID.randomUUID();
            repository.saveAndFlush(new InventoryStock(productId, 7));
            var first = repository.findById(productId).orElseThrow();
            var stale = repository.findById(productId).orElseThrow();
            // Simulate later domain mutations without exposing public counter setters in this delivery.
            ReflectionTestUtils.setField(first, "onHand", 8);
            var updated = repository.saveAndFlush(first);
            assertThat(updated.getVersion()).isEqualTo(1L);
            ReflectionTestUtils.setField(stale, "onHand", 9);

            assertThrows(OptimisticLockingFailureException.class, () -> repository.saveAndFlush(stale));
            var stored = repository.findById(productId).orElseThrow();
            assertThat(stored.getOnHand()).isEqualTo(8);
            assertThat(stored.getVersion()).isEqualTo(1L);
        });
    }

    // ApplicationContextRunner does not install the @SpringBootTest filter automatically.
    static class InventoryTestComponentFilter extends TypeExcludeFilter {
        @Override
        public boolean match(MetadataReader reader, MetadataReaderFactory factory) throws IOException {
            return new AnnotationTypeFilter(TestComponent.class).match(reader, factory);
        }

        @Override
        public boolean equals(Object other) {
            return other != null && other.getClass() == getClass();
        }

        @Override
        public int hashCode() {
            return getClass().hashCode();
        }
    }
}
